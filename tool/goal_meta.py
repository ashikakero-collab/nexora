#!/usr/bin/env python3
"""From the cut goal skins in assets/g/goals4/<id>.webp derive, per skin:
  * net_<id>.webp  - the honeycomb net between the crossbar, the ground bar and the posts (tileable-ish texture
                     used on the raised roof / back wall of the 3D match goal), 384 px wide;
  * a 4-stop frame palette sampled across the crossbar (dark edge, highlight, mid, dark edge);
  * the mean net colour.
and write lib/game/goal_skins_gen.dart. usage: tool/goal_meta.py id1 id2 ...
"""
import os, sys
import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
D = os.path.join(ROOT, 'assets', 'g', 'goals4')


def runs(mask):
    out, s = [], None
    for i, v in enumerate(list(mask) + [False]):
        if v and s is None:
            s = i
        elif not v and s is not None:
            out.append((s, i))
            s = None
    return out


def hexc(c):
    return '0xff%02x%02x%02x' % tuple(int(round(v)) for v in c)


def meta(id_):
    im = Image.open(os.path.join(D, id_ + '.webp')).convert('RGBA')
    a = np.asarray(im).astype(np.float32)
    al = a[..., 3] / 255
    h, w = al.shape
    band = al[:, int(w * .3):int(w * .7)]
    cov = (band > .5).mean(1)
    bars = [r for r in runs(cov > .85) if r[1] - r[0] >= 3]
    top = bars[0]
    bot = [r for r in bars if r[0] > top[1] + h * .2]
    bot = bot[0] if bot else (int(h * .78), int(h * .82))
    # crossbar palette: median colour of rows across the bar thickness at 4 depths
    cols = a[top[0]:top[1], int(w * .3):int(w * .7), :3]
    th = cols.shape[0]
    pal = [np.median(cols[min(th - 1, int(th * f))], axis=0) for f in (.05, .3, .6, .95)]
    # net box: rows between bars, columns between posts
    y0, y1 = top[1] + 2, bot[0] - 2
    rows = al[y0:y1]
    ccov = (rows > .5).mean(0)
    posts = [r for r in runs(ccov > .9) if r[1] - r[0] >= 3]
    lp = [r for r in posts if r[1] < w * .25]
    rp = [r for r in posts if r[0] > w * .75]
    x0 = (lp[-1][1] + 2) if lp else int(w * .1)
    x1 = (rp[0][0] - 2) if rp else int(w * .9)
    net = im.crop((x0, y0, x1, y1))
    nw = 384
    net = net.resize((nw, max(8, round(net.height * nw / net.width))), Image.LANCZOS)
    net.save(os.path.join(D, 'net_' + id_ + '.webp'), 'WEBP', quality=82, method=6)
    na = np.asarray(net).astype(np.float32)
    m = na[..., 3] > 128
    netc = na[..., :3][m].mean(0) if m.any() else np.array([220, 220, 220])
    cover = float(m.mean())
    print(id_, 'bars', top, bot, 'net box', (x0, y0, x1, y1), 'net', net.size, 'cover %.2f' % cover)
    return pal, netc, net.size


if __name__ == '__main__':
    ids = sys.argv[1:]
    lines = ['// GENERATED by tool/goal_meta.py from assets/g/goals4 - do not edit.',
             '// Per goal skin: crossbar palette (4 stops: edge, highlight, mid, edge), mean net colour, net texture size.',
             'const Map<String, (List<int>, int, int, int)> kGoalSkinMeta = {']
    for i in ids:
        pal, netc, (nw, nh) = meta(i)
        lines.append("  '%s': ([%s], %s, %d, %d)," % (i, ', '.join(hexc(c) for c in pal), hexc(netc), nw, nh))
    lines.append('};\n')
    open(os.path.join(ROOT, 'lib', 'game', 'goal_skins_gen.dart'), 'w').write('\n'.join(lines))
