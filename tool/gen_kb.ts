import * as K from '../../nexora-universe/src/oracle/kb';
import { writeFileSync } from 'fs';
const q = (s: string) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n') + "'";
let o = '// GENERATED by tool/gen_kb.ts from src/oracle/kb.ts (Oracle offline knowledge base).\npart of \'kb.dart\';\n\n';
o += 'const kActionLabel = <String, String>{\n' + Object.entries(K.ACTION_LABEL).map(([k, v]) => `  ${q(k)}: ${q(v)},`).join('\n') + '\n};\n';
o += 'const kSuggestions = [' + K.SUGGESTIONS.map(q).join(', ') + '];\n';
o += 'const kQuestionChips = [' + K.QUESTION_CHIPS.map(q).join(', ') + '];\n';
o += 'const kIntents = <Intent>[\n' + K.INTENTS.map(i => `  Intent(${q(i.id)}, [${i.kw.map(q).join(', ')}], ${q(i.answer)}, ${q(i.mood)}, [${(i.actions || []).map(q).join(', ')}]),`).join('\n') + '\n];\n';
o += 'const kActionKw = <(String, List<String>)>[\n' + K.ACTION_KW.map(([a, k]) => `  (${q(a)}, [${k.map(q).join(', ')}]),`).join('\n') + '\n];\n';
writeFileSync('lib/oracle/kb_gen.dart', o); console.log('ok', K.INTENTS.length);
